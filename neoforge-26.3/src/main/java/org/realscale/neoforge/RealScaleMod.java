package org.realscale.neoforge;

import net.neoforged.fml.common.Mod;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.neoforge.registries.RegisterEvent;
import net.neoforged.neoforge.common.NeoForge;
import org.realscale.neoforge.compat.dhchunky.DhChunkyGuardCommands;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.Identifier;

@Mod("realscale")
public final class RealScaleMod {
    public RealScaleMod(IEventBus bus) {
        bus.addListener(RealScaleStructurePacks::register);
        bus.addListener(this::registerDensity);
        NeoForge.EVENT_BUS.addListener(DhChunkyGuardCommands::registerCommands);
    }
    private void registerDensity(RegisterEvent event) {
        event.register(Registries.DENSITY_FUNCTION_TYPE, helper -> {
            // Fixed WGS84 1:20 latitude is the only model generated by Terrain Lab.
            // Legacy radial/climate-budget codecs remain registered only so old
            // saved datapacks can still deserialize; current paths never emit them.
            helper.register(Identifier.fromNamespaceAndPath("realscale", "dem_density"), RealDemDensity.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "dem_density_seamless"), RealDemSeamlessDensity.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "measured_horizontal_memo"), MeasuredHorizontalMemoDensity.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "grand_end_density"), GrandEndDensity.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "grand_nether_caverns"), GrandNetherCaverns.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "grand_overworld_caverns"), GrandOverworldCaverns.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "range_min_exact"), RangeMinDensity.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "mountain_relief"), MountainReliefDensity.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "terrain_archetype"), TerrainArchetypeDensity.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "ridge_erosion"), RidgeErosionDensity.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "strata"), StrataDensity.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "valley_temperature"), ValleyTemperatureDensity.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "latitude_temperature"), LatitudeTemperatureDensity.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "basin_temperature"), BasinTemperatureDensity.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "mountain_basin_temperature"), MountainBasinTemperatureDensity.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "radial_latitude_temperature"), RadialLatitudeTemperatureDensity.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "climate_budget"), ClimateBudgetDensity.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "fantasy_end_islands"), FantasyEndIslandsDensity.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "fantasy_nether_caverns"), FantasyNetherCavernsDensity.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "fantasy_end_archipelago"), FantasyEndArchipelagoDensity.MAP_CODEC);
        });
        event.register(Registries.BIOME_SOURCE, helper ->
            helper.register(Identifier.fromNamespaceAndPath("realscale", "geo_wonders_opt_in"),
                    GeoWondersBiomeSource.CODEC)
        );
        event.register(Registries.BIOME_SOURCE, helper ->
            helper.register(Identifier.fromNamespaceAndPath("realscale", "natural_ecotones"),
                    NaturalEcotoneBiomeSource.CODEC)
        );
event.register(Registries.BIOME_SOURCE, helper ->
            helper.register(Identifier.fromNamespaceAndPath("realscale", "sky_ocean"),
                    SkyOceanBiomeSource.CODEC)
        );
        event.register(Registries.BIOME_SOURCE, helper ->
            helper.register(Identifier.fromNamespaceAndPath("realscale", "cave_depth_habitats"),
                    CaveDepthBiomeSource.CODEC)
        );
        event.register(Registries.FEATURE_TYPE, helper -> {
            helper.register(Identifier.fromNamespaceAndPath("realscale", "river_channel"), RiverChannelFeature.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "vanilla_habitat"), VanillaHabitatFeature.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "ground_microstructure"), GroundMicrostructureFeature.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "sky_island"), SkyIslandFeature.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "habitat_patch"), HabitatPatchFeature.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "grand_ecology"), GrandEcologyFeature.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "cave_wonder_network"), CaveWonderNetworkFeature.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "geo_wonder_region"), GeoWonderRegionFeature.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "earth_wonder"), EarthWonderFeature.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "earth_systems_accent"), EarthSystemsAccentFeature.MAP_CODEC);
            helper.register(Identifier.fromNamespaceAndPath("realscale", "cave_marine_habitat"), CaveMarineHabitatFeature.MAP_CODEC);
        });
    }
}
