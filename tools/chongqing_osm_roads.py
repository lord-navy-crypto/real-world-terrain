#!/usr/bin/env python3
"""Source-traceable ROAD SURFACE footprints from official OpenStreetMap XML.

Original pilot used 1 Minecraft block for every OSM highway centerline, even
for multilane roads, making the city visually wrong. This module preserves
the actual OSM road centerline while constructing a plausible 2D road corridor.

Explicit OSM width gets HIGH geographic confidence. OSM lanes-derived or
highway-class default width gets LOW/MEDIUM confidence: NEVER call it a
surveyed curb edge. Elevated bridges, lower tunnels, nonzero layers and
waterfront vertical multilevel roads are DEFERRED, not projected on terrain.
Water and building footprints from the pinned V2 plan mask these projections.
No Google Maps, satellite pixels, OSM edits or autogenerated roads.
"""
from __future__ import annotations
import argparse
import collections
import gzip
import hashlib
import json
import math
import re
from pathlib import Path
import urllib.request
import xml.etree.ElementTree as ET

from chongqing_osm_to_minecraft import Dem, DEFAULT_DEM
from chongqing_fetch_osm_api import bounds

FORMAT="REALSCALE_CHAOTIANMEN_ROAD_CORRIDORS_V1"
RADIUS=500
MAX_XML_BYTES=8*1024*1024

# Approximate cartographic carriageway widths, NOT surveyed dimensions.
DEFAULT_WIDTH={
    "motorway":12,"trunk":11,"primary":9,"secondary":8,
    "tertiary":7,"unclassified":5,"residential":5,
    "living_street":4,"service":3,"pedestrian":4,
    "footway":2,"path":1.5,"cycleway":2,"steps":1.5,
    "track":3,
    "motorway_link":6,"trunk_link":6,"primary_link":5,
    "secondary_link":5,"tertiary_link":5}
PAVING={
    "asphalt":"asphalt","concrete":"concrete","paving_stones":"paving",
    "paved":"paving","sett":"paving","cobblestone":"paving",
    "gravel":"gravel","fine_gravel":"gravel","compacted":"gravel",
    "ground":"dirt","dirt":"dirt","earth":"dirt",
    "grass":"grass","wood":"wooden_paving"}

def parse_width(tags):
    """Width in *metres*, confidence and evidence source."""
    value=tags.get("width","").strip().lower()
    if re.fullmatch(r"\d+(?:\.\d+)?(?:\s*m)?",value):
        width=float(value.removesuffix("m").strip())
        if 0.75<=width<=18:
            return width,"high","osm_width_m"
    lanes=tags.get("lanes","")
    if re.fullmatch(r"[1-6]",lanes):
        return min(18.0,3.2*int(lanes)),"medium","osm_lanes_estimate"
    kind=tags.get("highway")
    if kind in DEFAULT_WIDTH:
        return DEFAULT_WIDTH[kind],"low","highway_class_inference"
    return None

def width_mask(points,width,radius=RADIUS):
    """Rasterize a corridor around real projected geodetic OSM segments.

    Pixel center is the 1m Minecraft cell center. No endpoints outside
    source bounds and no faux 1m precision assertions from OSM lane defaults.
    """
    half=width/2
    cells=set()
    for (ax,az),(bx,bz) in zip(points,points[1:]):
        dx=bx-ax;dz=bz-az
        norm=dx*dx+dz*dz
        if norm>1e10:raise ValueError("Impossible OSM segment length")
        min_x=max(-radius,math.floor(min(ax,bx)-half-1))
        max_x=min(radius,math.ceil(max(ax,bx)+half+1))
        min_z=max(-radius,math.floor(min(az,bz)-half-1))
        max_z=min(radius,math.ceil(max(az,bz)+half+1))
        for z in range(min_z,max_z+1):
            for x in range(min_x,max_x+1):
                px=x+0.5; pz=z+0.5
                u=0 if norm==0 else min(1,max(0,
                       ((px-ax)*dx+(pz-az)*dz)/norm))
                distance2=(px-(ax+u*dx))**2+(pz-(az+u*dz))**2
                if distance2 <=half*half:
                    cells.add((x,z))
    return cells

def classify_osm_roads(xml,dem,radius=RADIUS):
    if radius not in (500,600):raise ValueError("Unverified OSM highway radius")
    if len(xml)>MAX_XML_BYTES:raise ValueError("OSM source larger than 8MB")
    root=ET.fromstring(xml)
    if root.tag!="osm" or root.get("version")!="0.6":
        raise ValueError("Expected official OSM 0.6 XML")
    if "odbl" not in (root.get("license") or "").lower():
        raise ValueError("Source is missing OSM ODbL provenance")
    nodes={}
    for n in root.findall("node"):
        nodes[n.get("id")]=(float(n.get("lon")),float(n.get("lat")))
    kinds=collections.Counter()
    deferred=collections.Counter()
    candidates=[]
    for way in root.findall("way"):
        tags={v.get("k"):v.get("v") for v in way.findall("tag")}
        if "highway" not in tags:
            continue
        if (tags.get("bridge","no")!="no"
                or tags.get("tunnel","no")!="no"
                or tags.get("layer","0") not in ("0","0.0")
                or tags.get("covered","no")=="yes"):
            deferred["elevated_or_buried"]+=1
            continue
        width=parse_width(tags)
        if width is None:
            deferred["unknown_road_width_or_type"]+=1
            continue
        refs=[n.get("ref") for n in way.findall("nd")]
        if len(refs)<2 or any(r not in nodes for r in refs):
            deferred["incomplete_nodes"]+=1
            continue
        points=[dem.coords(*nodes[n]) for n in refs]
        cells=width_mask(points,width[0],radius)
        if not cells:continue
        source="way/"+str(way.get("id"))
        material=PAVING.get(tags.get("surface"),None)
        if material is None:
            material="paving" if tags.get("highway") in (
                "footway","pedestrian","path","steps") else "asphalt"
        candidates.append((source,tags.get("highway"),width,material,cells))
        kinds[tags["highway"]]+=1
    # Preserve a deterministic result independent of XML element order.
    # Explicit widths have priority at crossings; centerlines override
    # inferred road area, but building masks are applied LATER by exporter.
    priority={"low":0,"medium":1,"high":2}
    cells={}
    for source,highway,width,material,footprint in sorted(
            candidates,key=lambda t:(priority[t[2][1]],t[0])):
        for xy in footprint:
            cells[xy]=(material,width[1],source,width[2])
    rows=[]
    count=collections.Counter()
    for z in range(-radius,radius+1):
        x=-radius
        while x<=radius:
            rec=cells.get((x,z))
            if rec is None:
                x+=1;continue
            end=x
            while end<radius and cells.get((end+1,z))==rec:
                end+=1
            rows.append([z,x,end,*rec])
            count[rec[0]]+=end-x+1
            x=end+1
    return {
        "format":FORMAT,
        "radius_m":radius,"resolution_m":1,
        "origin_lat":dem.lat,"origin_lon":dem.lon,
        "dem_source_raw_sha256":dem.sha256,
        "raw_osm_api_sha256":hashlib.sha256(xml).hexdigest(),
        "license":"ODbL-1.0","attribution":"© OpenStreetMap contributors",
        "width_note":"tagged high; lane-estimate medium; inferred OSM highway type LOW; not surveyed curbs",
        "classified_road_surface_cells":len(cells),
        "road_surface_materials":dict(count),
        "osm_road_type_count":dict(kinds),
        "deferred_road_types":dict(deferred),
        "rows":rows,
    }

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--input-xml",type=Path)
    ap.add_argument("--output",type=Path,required=True)
    ap.add_argument("--radius",type=int,choices=(500,600),default=500)
    args=ap.parse_args()
    dem=Dem(DEFAULT_DEM)
    bbox,url=bounds(dem,args.radius,100)
    if args.input_xml:
        raw=args.input_xml.read_bytes()
        src="offline_user_supplied_official_OSM_XML"
    else:
        req=urllib.request.Request(url,headers={
            "User-Agent":"RealScale-Chaotianmen-GIS-Road-Research/1.0 ODbL",
            "Accept":"application/xml"})
        with urllib.request.urlopen(req,timeout=60) as response:
            raw=response.read(MAX_XML_BYTES+1)
        src=url
    result=classify_osm_roads(raw,dem,radius=args.radius)
    result["source_url"]=src;result["query_bbox_wsen"]=bbox
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_bytes(gzip.compress(
        json.dumps(result,sort_keys=True,separators=(",",":"),
                   ensure_ascii=False).encode("utf8"),mtime=0,compresslevel=9))
    print("CHONGQING_SOURCE_ROAD_CORRIDORS",json.dumps({
        k:v for k,v in result.items() if k!="rows"},ensure_ascii=False))

if __name__=="__main__":main()
