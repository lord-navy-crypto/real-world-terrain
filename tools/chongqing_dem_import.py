#!/usr/bin/env python3
"""
Import an authentic georeferenced DEM GeoTIFF into RealScale Special Chongqing.

Example (requires Python numpy, rasterio, pyproj installed locally):
 python3 tools/chongqing_dem_import.py \
   --dem real_chongqing_copernicus_mosaic.tif \
   --citation "Copernicus DEM GLO-30, accessed YYYY-MM-DD, source URL" \
   --license "Copernicus DEM ESA User License" \
   --output neoforge/src/main/resources/assets/realscale/terrain/chongqing_chaotianmen_dem_v1.properties

WORLD X = east metres, WORLD Z = south metres, 0,0 = Chaotianmen.
Do not infer elevation outside the input DEM; nodata is an ERROR. The
GeoTIFF must cover the full 129x129 64-metre grid (approx 8.2 km square).
No OSM roads/buildings/water are invented by this script.
"""
import argparse
import base64
import gzip
import hashlib
import struct
from pathlib import Path

CENTER_LON = 106.5874
CENTER_LAT = 29.5667
WIDTH = 129
STEP_METRES = 64
MIN_X = MIN_Z = -4096

def build(dem: Path, citation: str, license_name: str):
    try:
        import numpy as np
        import rasterio
        from pyproj import Transformer
        from rasterio.enums import Resampling
        from rasterio.transform import Affine
        from rasterio.warp import reproject
    except ImportError as error:
        raise SystemExit("Install rasterio, pyproj, numpy to convert real DEMs") from error

    if not citation.strip() or not license_name.strip():
        raise ValueError("Explicit real source citation and license are required")
    if not dem.is_file():
        raise ValueError("Specified GeoTIFF does not exist: " + str(dem))
    centre_e, centre_n = Transformer.from_crs(
        "EPSG:4326", "EPSG:32648", always_xy=True
    ).transform(CENTER_LON, CENTER_LAT)
    # Affine points at pixel upper-left corner; the centre of pixel (0,0)
    # must correspond to MC (-4096,-4096), at 1:1 horizontal metre scale.
    destination_transform = Affine(
        STEP_METRES, 0, centre_e + MIN_X - STEP_METRES / 2,
        0, -STEP_METRES, centre_n - MIN_Z + STEP_METRES / 2,
    )
    dst = np.full((WIDTH,WIDTH), np.float32(-32768), dtype=np.float32)
    with rasterio.open(dem) as source:
        if source.crs is None:
            raise ValueError("GeoTIFF has no CRS; refusing to guess geography")
        reproject(
            source=rasterio.band(source,1),
            destination=dst,
            src_transform=source.transform,
            src_crs=source.crs,
            src_nodata=source.nodata,
            dst_transform=destination_transform,
            dst_crs="EPSG:32648",
            dst_nodata=-32768,
            resampling=Resampling.bilinear,
            init_dest_nodata=True,
        )
    if not np.isfinite(dst).all() or (dst <= -32768).any():
        raise ValueError("DEM coverage/nodata holes; refusing fictional interpolation")
    if not ((dst>-1000).all() and (dst<6000).all()):
        raise ValueError("DEM has implausible heights; inspect CRS and units")
    rounded = np.rint(dst).astype(">i2",copy=False)
    raw = rounded.tobytes()
    compressed = gzip.compress(raw,compresslevel=9,mtime=0)
    meta = {
        "format":"CQDEM1",
        "width":str(WIDTH),
        "spacing_m":str(STEP_METRES),
        "min_x":str(MIN_X),
        "min_z":str(MIN_Z),
        "center_lat":str(CENTER_LAT),
        "center_lon":str(CENTER_LON),
        "source_zoom":"GeoTIFF",
        "source_license":license_name.strip(),
        "source_citation":citation.strip(),
        "source_file_sha256":hashlib.sha256(dem.read_bytes()).hexdigest(),
        "source_raw_sha256":hashlib.sha256(raw).hexdigest(),
        "heights_gzip_base64":base64.b64encode(compressed).decode("ascii"),
    }
    return (
        "# Authentic Chongqing DEM import: local UTM zone 48N coordinates.\n"
        "# Generated by tools/chongqing_dem_import.py, no synthetic elevations.\n"
        + "\n".join(f"{k}={v}" for k,v in meta.items())+"\n"
    )

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--dem",type=Path,required=True,
                   help="Authentic GeoTIFF raster, EPSG/CRS must be present")
    p.add_argument("--citation",required=True,
                   help="Dataset author, date and official source URL")
    p.add_argument("--license",required=True,
                   help="Applicable real-data usage license/attribution")
    p.add_argument("--output",type=Path,required=True)
    args=p.parse_args()
    for value in (args.citation,args.license):
        if "\n" in value or "\r" in value or "=" in value:
            p.error("Citation/license must be one line with no '='")
    data=build(args.dem,args.citation,args.license)
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(data,encoding="ascii")
    print("Chongqing REAL DEM resource written:",args.output)
    print("Metadata and raster SHA-256 included; inspect the diff before commit")
    print("WARNING: Replacing bundled DEM changes world blocks. Use a NEW world.")

if __name__=="__main__":
    main()
